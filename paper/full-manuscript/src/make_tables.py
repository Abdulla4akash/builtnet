@dataclass
class Table:
    name: str
    caption: str
    widths: tuple[float, ...]
    columns: tuple[str, ...]
    rows: list


def code(s):
    return r'\texttt{' + s.replace('_', r'\_') + '}'


def write(table):
    assert all(len(row) == len(table.columns) for row in table.rows), table.name
    spec = ' '.join(r'>{\raggedright\arraybackslash}p{' + str(w) + r'\linewidth}' for w in table.widths)
    header = r'\rowcolor{tableblue} ' + ' & '.join(r'\textbf{' + s + '}' for s in table.columns)
    text = ['% Generated by src/make_tables.py.', r'\begin{table}[!htbp]', r'\centering\small',
            r'\caption{' + table.caption + '}', r'\label{tab:' + table.name + '}',
            r'\begin{tabular}{@{} ' + spec + ' @{}}', r'\toprule', header + r' \\', r'\midrule']
    text.extend(' & '.join(map(str, row)) + r' \\' for row in table.rows)
    text.extend([r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])
    (PAPER / 'tables' / f'{table.name}.tex').write_text('\n'.join(text))


